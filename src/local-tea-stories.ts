// 单机茶馆的旧闻，不依赖推理、图片或联网；沿用听书年岁与赠礼结算。
const STORIES = [
  '青岚渡口曾有一位摆渡老人，船头挂着一盏从不熄灭的灯。有人说他认得通往仙山的水路，许以重金，只求渡上一程。老人摇头，只把船撑向对岸。后来山中有修士归来，认出那灯是失落多年的灵宝，伸手便要取走。老人没有争，只问他，还记不记得少年时，是谁在风雪里渡他过河。那人站了许久，终于收回手。再后来，渡口换了新船，灯也不见了。茶馆里的人各有猜测，只有卖鱼的说，那晚河上很亮，像有人把一生的月光，都还给了故乡。',
  '两名同门在古洞里寻得一枚灵丹，约好出山后平分所得。归途遇险，一人受了重伤，另一人却将丹药藏进袖中，说此丹关乎大道，不能轻用。伤者没有求他，只借了一口水，独自留在山下。数十年后，携丹者突破未成，重访故地，看见山下多了一间药庐。庐主仍是当年的同门，修为未进，却已救过许多人。他忽然想起，那日自己走得太急，竟连那口水的水囊也带走了。临别时他留下灵丹，庐主没有推辞，只取来药秤，称了称这味迟到的药。',
  '北山有位剑修，闭关百年，只为赴一场旧约。出关时，约战之人早已坐化，山门也成了荒草。他不肯相信，仍在石阶上等。春去秋来，有个采药孩子常来问他，仙人为何总不回家。剑修说，有人还欠我一剑。孩子想了想，把一枝桃花放在他膝前，说那就先欠着吧，花快谢了。那天剑修终于下山。后来有人在江边见过他，长剑还在，剑鞘上却别着一枝木雕的桃花。他依旧寻道，只是不再把每个春天，都用来等一个不会来的人。',
] as const;

export function localTeaStory(seed: number, age: number): string {
  const index =
    (((Math.trunc(seed) + Math.floor(age * 2)) % STORIES.length) + STORIES.length) % STORIES.length;
  return STORIES[index]!;
}
